/**
 * Generates an array of validated parameterized items for a specified template.
 */
export function generateParameterizedItems(templateKey, count = 3, baseSeed = 500) {
  const tpl = TEMPLATES[templateKey];
  if (!tpl) return [];
  const items = [];
  for (let i = 0; i < count; i++) {
    items.push(tpl.generate(baseSeed + i * 17));
  }
  return items;
}

